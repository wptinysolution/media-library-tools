/**
 * CSV output for the admin media exports, safe to open in a spreadsheet.
 *
 * A text cell that a spreadsheet would run as a formula — it starts with =, +,
 * -, @, a tab or a carriage return, optionally after apostrophes — gets one
 * leading apostrophe. Values that already start with apostrophes before such a
 * character get one more, so the original text can always be recovered by
 * removing exactly one apostrophe (the rule the Pro MCP CSV import uses).
 * Number columns are never changed, so a negative menu order stays a number.
 */
import Papa from 'papaparse';

/** A cell a spreadsheet may run as a formula. */
const FORMULA_START = /^'*[=+\-@\t\r]/;

/** Columns that hold numbers generated by the plugin; never protected. */
export const NUMERIC_COLUMNS: readonly string[] = ['ID', 'post_parent', 'menu_order'];

/** Prefix a text cell with an apostrophe when a spreadsheet would run it. */
export const protectCsvCell = (value: string): string =>
    FORMULA_START.test(value) ? `'${value}` : value;

/** Objects and arrays as JSON text; other values unchanged. */
export const escapeValues = (obj: Record<string, unknown>): Record<string, unknown> => {
    const escaped: Record<string, unknown> = {};
    for (const key in obj) {
        const value = obj[key];
        escaped[key] = typeof value === 'object' && value !== null ? JSON.stringify(value) : value;
    }
    return escaped;
};

/** Protect every text cell of a row, except the number columns. */
export const protectCsvRow = (row: Record<string, unknown>): Record<string, unknown> => {
    const safe: Record<string, unknown> = {};
    for (const key in row) {
        const value = row[key];
        safe[key] = typeof value === 'string' && !NUMERIC_COLUMNS.includes(key) ? protectCsvCell(value) : value;
    }
    return safe;
};

/** Rows (one object per attachment) as quoted CSV text, safe for spreadsheets. */
export const toSafeCsv = (rows: Record<string, unknown>[]): string =>
    Papa.unparse(rows.map(row => protectCsvRow(escapeValues(row))), { quotes: true });
